// ACT Math: rules and playbook.
// Written from ACT's own descriptions of the test (the enhanced ACT, 2025 on) and its official practice
// materials, plus well-known prep guidance. Each rule is one thing a student can learn and reuse.
//
// Test facts these rules assume:
// - Enhanced ACT (2025 on): 45 questions in 50 minutes, 4 choices, a few unscored field-test questions mixed in.
//   Preparing for Higher Math is about 80% (Number and Quantity, Algebra, Functions, Geometry, Statistics and
//   Probability); Integrating Essential Skills is about 20%; Modeling is a cross-cutting tag on at least about 20%.
// - Legacy ACT (older practice tests): 60 questions in 60 minutes, 5 choices (A-E on odd questions, F-K on even).
// - A calculator is allowed on the whole section; the online ACT has a built-in Desmos graphing calculator, paper
//   testers bring their own; calculators with a computer algebra system are banned. No formula sheet is given.
// - Directions: illustrative figures are NOT necessarily drawn to scale; figures lie in a plane; "line" means a
//   straight line; "average" means arithmetic mean.
